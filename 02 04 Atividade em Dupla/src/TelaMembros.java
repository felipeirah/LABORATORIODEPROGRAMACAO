    /**
    * Atualiza a JTable com os registros armazenados na Biblioteca.
    * Cria as colunas e adiciona uma linha para cada registro do modelo.
    */
    private void atualizarTabela() {
        javax.swing.table.DefaultTableModel modelo =
            new javax.swing.table.DefaultTableModel(
                new Object[]{"ID", "Nome", "Matrícula", "Contato"}, 0
            ) {
                @Override
                public boolean isCellEditable(int linha, int coluna) {
                    return false;
                }
            };

        for (Membro membro : biblioteca.getMembros()) {
            modelo.addRow(new Object[]{
                membro.getId(),
                membro.getNome(),
                membro.getMatricula(),
                membro.getTelefone()
            });
        }

        jtMembros.setModel(modelo);
    }

