    // Valida os campos e cadastra um novo Membro na Biblioteca.
    private void jbCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbCadastrarActionPerformed
        // TODO add your handling code here:
        String nome = jtfNome.getText().trim();
        String matricula = jtfMatricula.getText().trim();
        String contato = jtfContato.getText().trim();

        if (nome.isEmpty() || matricula.isEmpty() || contato.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos.");
            return;
        }

        int proximoId = 1;
        for (Membro membro : biblioteca.getMembros()) {
            if (matricula.equalsIgnoreCase(membro.getMatricula())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Essa matrícula já está cadastrada.");
                return;
            }
            proximoId = Math.max(proximoId, membro.getId() + 1);
        }

        // O modelo anterior exige e-mail no construtor; esta atividade pede contato.
        Membro membro = new Membro(proximoId, nome, "", contato);
        membro.setMatricula(matricula);
        biblioteca.cadastrarMembro(membro);

        atualizarTabela();
        jtfNome.setText("");
        jtfMatricula.setText("");
        jtfContato.setText("");

        javax.swing.JOptionPane.showMessageDialog(this, "Membro cadastrado com sucesso.");
    }//GEN-LAST:event_jbCadastrarActionPerformed
    
    // Atualiza os dados do membro selecionado na tabela.
    private void jbEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEditarActionPerformed
        // TODO add your handling code here:
        int linha = jtMembros.getSelectedRow();
        if (linha < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um membro na tabela.");
            return;
        }

        int linhaModelo = jtMembros.convertRowIndexToModel(linha);
        int id = (int) jtMembros.getModel().getValueAt(linhaModelo, 0);

        String nome = jtfNome.getText().trim();
        String matricula = jtfMatricula.getText().trim();
        String contato = jtfContato.getText().trim();

        if (nome.isEmpty() || matricula.isEmpty() || contato.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos.");
            return;
        }

        for (Membro outro : biblioteca.getMembros()) {
            if (outro.getId() != id
                    && matricula.equalsIgnoreCase(outro.getMatricula())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Essa matrícula já pertence a outro membro.");
                return;
            }
        }

        Membro membro = biblioteca.buscarMembroPorId(id);
        if (membro == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Membro não encontrado.");
            return;
        }

        biblioteca.editarMembro(id, nome, membro.getEmail(), contato);
        membro.setMatricula(matricula);

        atualizarTabela();
        jtfNome.setText("");
        jtfMatricula.setText("");
        jtfContato.setText("");

        javax.swing.JOptionPane.showMessageDialog(this, "Membro atualizado com sucesso.");
    }//GEN-LAST:event_jbEditarActionPerformed
    
    // Ao clicar em uma linha da tabela, carrega os dados do membro nos campos
    // do formulário para permitir sua edição.
    private void jtMembrosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtMembrosMouseClicked
        // TODO add your handling code here:
        int linha = jtMembros.getSelectedRow();
        if (linha < 0) {
            return;
        }

        int linhaModelo = jtMembros.convertRowIndexToModel(linha);
        int id = (int) jtMembros.getModel().getValueAt(linhaModelo, 0);
        Membro membro = biblioteca.buscarMembroPorId(id);

        if (membro != null) {
            jtfNome.setText(membro.getNome());
            jtfMatricula.setText(membro.getMatricula());
            jtfContato.setText(membro.getTelefone());
        }
    }//GEN-LAST:event_jtMembrosMouseClicked

