    //Fazer as informações aparecer na tabela
    private void atualizarOpcoes() {
        jcbLivro.removeAllItems();
        jcbMembro.removeAllItems();

        for (Livro livro : biblioteca.getLivros()) {
            if (livro.getDisponivel()) {
                jcbLivro.addItem(livro.getId() + " - " + livro.getTitulo());
            }
        }

        for (Membro membro : biblioteca.getMembros()) {
            jcbMembro.addItem(membro.getId() + " - " + membro.getNome());
        }

        jcbLivro.setSelectedIndex(-1);
        jcbMembro.setSelectedIndex(-1);
    }
    
    /**
    * Atualiza a JTable com os registros armazenados na Biblioteca.
    * Cria as colunas e adiciona uma linha para cada registro do modelo.
    */
    private void atualizarTabela() {
        javax.swing.table.DefaultTableModel modelo =
            new javax.swing.table.DefaultTableModel(
                new Object[]{"ID", "Livro", "Membro", "Empréstimo", "Devolução", "Status"}, 0
            ) {
                @Override
                public boolean isCellEditable(int linha, int coluna) {
                    return false;
                }
            };

        for (Emprestimo emprestimo : biblioteca.getEmprestimos()) {
            modelo.addRow(new Object[]{
                emprestimo.getId(),
                emprestimo.getLivro().getTitulo(),
                emprestimo.getMembro().getNome(),
                emprestimo.getDataEmprestimo(),
                emprestimo.getDataDevolucao() == null
                    ? ""
                    : emprestimo.getDataDevolucao(),
                emprestimo.isAtivo() ? "Ativo" : "Encerrado"
            });
        }

        jtEmprestimos.setModel(modelo);
    }

