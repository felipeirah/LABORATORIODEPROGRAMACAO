    // Valida as seleções e registra na Biblioteca o empréstimo do livro ao membro.
    private void jbRealizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbRealizarActionPerformed
        // TODO add your handling code here:
        if (jcbLivro.getSelectedItem() == null || jcbMembro.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Selecione um livro e um membro.");
            return;
        }

        String livroSelecionado = (String) jcbLivro.getSelectedItem();
        String membroSelecionado = (String) jcbMembro.getSelectedItem();

        int idLivro = Integer.parseInt(livroSelecionado.split(" - ", 2)[0]);
        int idMembro = Integer.parseInt(membroSelecionado.split(" - ", 2)[0]);

        int novoId = 1;
        for (Emprestimo emprestimo : biblioteca.getEmprestimos()) {
            novoId = Math.max(novoId, emprestimo.getId() + 1);
        }

        biblioteca.realizarEmprestimo(novoId, idLivro, idMembro);
        atualizarOpcoes();
        atualizarTabela();

        JOptionPane.showMessageDialog(this, "Empréstimo realizado com sucesso!");
    }//GEN-LAST:event_jbRealizarActionPerformed

    // Encerra o empréstimo selecionado na tabela e torna o livro disponível novamente.
    private void jbEncerrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEncerrarActionPerformed
        // TODO add your handling code here:
        int linha = jtEmprestimos.getSelectedRow();
        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um empréstimo na tabela.");
            return;
        }

        int linhaModelo = jtEmprestimos.convertRowIndexToModel(linha);
        int id = (int) jtEmprestimos.getModel().getValueAt(linhaModelo, 0);

        for (Emprestimo emprestimo : biblioteca.getEmprestimos()) {
            if (emprestimo.getId() == id && !emprestimo.isAtivo()) {
                JOptionPane.showMessageDialog(this, "Esse empréstimo já foi encerrado.");
                return;
            }
        }

        biblioteca.encerrarEmprestimo(id);
        atualizarOpcoes();
        atualizarTabela();

        JOptionPane.showMessageDialog(this, "Empréstimo encerrado com sucesso!");
    }//GEN-LAST:event_jbEncerrarActionPerformed

